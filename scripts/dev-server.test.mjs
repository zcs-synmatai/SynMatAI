import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { request } from 'node:http';
import { createDevServer } from './dev-server.mjs';

test('development server protects the prototype behind the configured login', async t => {
  const credentials = { enabled:true, username:'test-user', password:'test-password', sessionHours:1 };
  const server = createDevServer(credentials); server.listen(0,'127.0.0.1'); await once(server,'listening');
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const base = `http://127.0.0.1:${server.address().port}`;
  const entry = await fetch(base);
  assert.equal(entry.status,200); assert.match(await entry.text(),/auth-form/);
  assert.equal((await fetch(base+'/src/styles/auth.css')).status,200);
  assert.equal((await fetch(base+'/src/features/workflow/workbench.js')).status,401);
  const rejected = await fetch(base+'/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:'demo',password:'wrong'})});
  assert.equal(rejected.status,401);
  const accepted = await fetch(base+'/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:credentials.username,password:credentials.password})});
  assert.equal(accepted.status,200);
  const cookie = accepted.headers.get('set-cookie').split(';')[0];
  const auth = { headers:{ cookie } };
  const app = await fetch(base,auth);
  assert.equal(app.status,200); assert.match(await app.text(),/src\/styles\/main.css/);
  const css = await fetch(base+'/src/styles/main.css');
  assert.equal(css.status,401);
  const protectedCss = await fetch(base+'/src/styles/main.css',auth);
  assert.equal(protectedCss.status,200); assert.match(protectedCss.headers.get('content-type'),/text\/css/);
  const logo = await fetch(base+'/assets/brand/synmatai-logo.png',auth);
  assert.equal(logo.status,200); assert.equal(logo.headers.get('content-type'),'image/png');
  assert.equal((await fetch(base+'/src/features/workflow/workbench.js',auth)).status,200);
  assert.equal((await fetch(base+'/package.json',auth)).status,404);
  assert.equal((await fetch(base+'/.env')).status,400);
  assert.equal((await fetch(base+'/missing',auth)).status,404);
  assert.equal((await fetch(base,{method:'POST'})).status,405);
  const head = await fetch(base,{method:'HEAD',headers:{cookie}});
  assert.equal(head.status,200); assert.equal(await head.text(),'');
  const traversal = await new Promise((resolve,reject) => {
    const req = request(base,{path:'/src/%2e%2e%5c%2e%2e%5cpackage.json',headers:{cookie}},res=>{res.resume();resolve(res.statusCode);});
    req.on('error',reject);req.end();
  });
  assert.equal(traversal,400);
  const logout = await fetch(base+'/auth/logout',{method:'POST',headers:{cookie}});
  assert.equal(logout.status,200); assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
});
